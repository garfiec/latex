/**
 * Scores every corpus formula against KaTeX's render of it with RaTeX's ink metric.
 *
 * Needs the references from `test-corpus/fetch-katex-references.sh` (skipped without them).
 * Fails when a formula scores more than [TOLERANCE] below `test-corpus/katex-fidelity-baseline.tsv`;
 * `UPDATE_FIDELITY_BASELINE=1` rewrites the baseline. The report, our renders and side-by-side
 * comparisons of the lowest scores go to `build/reports/katex-fidelity`.
 */
class KatexFidelityTest {

    private data class Suite(val corpus: String, val references: String, val fontPx: Int, val prooftree: Boolean = false) {
        val name = corpus.removeSuffix(".txt")
    }

    private data class Result(val suite: String, val index: Int, val formula: String, val score: InkMetric.Score)

    @Test
    fun corpusScoresHoldTheBaseline() {
        val references = File(System.getProperty("latex.katex.references") ?: File(root, "build/katex-references").path)
        assumeTrue("No KaTeX references in $references: run test-corpus/fetch-katex-references.sh", references.isDirectory)
        val reportDir = File(root, "latex-renderer/build/reports/katex-fidelity").apply { deleteRecursively(); mkdirs() }

        val results = SUITES.flatMap { suite -> score(suite, File(references, suite.references), reportDir) }
        val ratex = ratexScores(File(references, "ratex-scores.json"))
        writeReport(results, ratex, reportDir)

        val baselineFile = File(root, "test-corpus/katex-fidelity-baseline.tsv")
        if (System.getenv("UPDATE_FIDELITY_BASELINE") != null) {
            baselineFile.writeText(
                "# suite\tindex\tscore (generated by KatexFidelityTest; UPDATE_FIDELITY_BASELINE=1 rewrites it)\n" +
                    results.joinToString("") { "${it.suite}\t${it.index}\t${format(it.score.score)}\n" },
            )
            return
        }
        val baseline = baselineFile.readLines().filter { it.isNotBlank() && !it.startsWith("#") }.associate { line ->
            val (suite, index, score) = line.split('\t')
            (suite to index.toInt()) to score.toDouble()
        }
        val regressions = results.filter { r -> baseline[r.suite to r.index]?.let { r.score.score < it - TOLERANCE } ?: false }
        val improved = results.count { r -> baseline[r.suite to r.index]?.let { r.score.score > it + TOLERANCE } ?: false }
        println("KaTeX fidelity: mean ${format(results.map { it.score.score }.average())}, $improved above the baseline")
        if (regressions.isNotEmpty()) {
            fail(
                "${regressions.size} formulas score more than $TOLERANCE below the baseline " +
                    "(see ${reportDir.path}):\n" + regressions.joinToString("\n") { r ->
                        "  ${r.suite} #${r.index}: ${format(baseline.getValue(r.suite to r.index))} -> ${format(r.score.score)}  ${r.formula}"
                    },
            )
        }
    }

    private fun score(suite: Suite, references: File, reportDir: File): List<Result> {
        val config = LatexConfig(fontSize = (suite.fontPx * KATEX_EM_SCALE).sp, theme = LatexTheme.light(color = Color.Black, backgroundColor = Color.White))
        val renders = File(reportDir, "renders/${suite.name}").apply { mkdirs() }
        return RendererRobustnessTest.corpus(listOf(suite.corpus)).mapIndexed { i, (_, formula) ->
            val index = i + 1
            val name = String.format(Locale.ROOT, "%04d.png", index)
            val reference = File(references, name)
            check(reference.isFile) { "Missing KaTeX reference ${reference.path}: the references do not match the corpus" }
            val bytes = exporter.export(formula, config, ExportConfig(scale = 2f))?.bytes
            bytes?.let { File(renders, name).writeBytes(it) }
            val test = bytes?.let { ImageIO.read(ByteArrayInputStream(it)) } ?: BLANK
            val score = InkMetric.score(InkMetric.Raster.of(ImageIO.read(reference)), InkMetric.Raster.of(test), suite.prooftree)
            Result(suite.name, index, formula, score)
        }
    }

    private fun writeReport(results: List<Result>, ratex: List<Double?>, reportDir: File) {
        File(reportDir, "scores.tsv").writeText(
            "suite\tindex\tscore\tiou\trecall\tprecision\taspect\twidth\tratex\tformula\n" + results.joinToString("") { r ->
                val s = r.score
                val theirs = if (r.suite == "main") ratex.getOrNull(r.index - 1)?.let(::format) ?: "" else ""
                "${r.suite}\t${r.index}\t${format(s.score)}\t${format(s.iou)}\t${format(s.recall)}\t${format(s.precision)}\t" +
                    "${format(s.aspectSimilarity)}\t${format(s.widthSimilarity)}\t$theirs\t${r.formula}\n"
            },
        )

        // Unsupported formulas draw their source in the error colour; the coverage ratchet tracks them.
        val unsupported = File(root, "test-corpus/ratex/unsupported-baseline.txt").readLines().toSet()
        val parsed = results.filter { it.formula !in unsupported }

        val report = StringBuilder("# KaTeX fidelity\n\n")
        report.append("RaTeX `ratex-ink-v2` score against KaTeX 0.16.45 renders (1.0 is identical ink). Chrome draws glyphs ")
        report.append("heavier than Compose's Skia text, so a formula laid out exactly like KaTeX still scores about 0.8–0.9, ")
        report.append("and the means are not comparable with RaTeX's own. Parsed means formulas the parser accepts without ")
        report.append("an error or unknown command.\n\n")
        report.append("| Suite | Formulas | Mean | Parsed | Parsed mean | Parsed median | Parsed < 0.7 | Parsed < 0.5 |\n")
        report.append("|---|---|---|---|---|---|---|---|\n")
        for ((suite, group) in results.groupBy { it.suite } + ("all" to results)) {
            val clean = group.filter { it.formula !in unsupported }.map { it.score.score }.sorted()
            report.append("| $suite | ${group.size} | ${format(group.map { it.score.score }.average())} | ${clean.size} | ")
            if (clean.isEmpty()) report.append("– | – | – | – |\n") else {
                report.append("${format(clean.average())} | ${format(clean[clean.size / 2])} | ")
                report.append("${clean.count { it < 0.7 }} | ${clean.count { it < 0.5 }} |\n")
            }
        }
        val paired = parsed.filter { it.suite == "main" }.mapNotNull { r -> ratex.getOrNull(r.index - 1)?.let { r to it } }
        if (paired.isNotEmpty()) {
            report.append("\n## Parsed formulas furthest behind RaTeX\n\nRaTeX's score for the same formula, from its golden baseline.\n\n")
            report.append("| # | Ours | RaTeX | Formula |\n|---|---|---|---|\n")
            for ((r, theirs) in paired.sortedByDescending { it.second - it.first.score.score }.take(WORST)) {
                report.append("| ${r.index} | ${format(r.score.score)} | ${format(theirs)} | `${r.formula.replace("|", "\\|")}` |\n")
            }
        }
        report.append("\n## Lowest-scoring parsed formulas\n\nSide by side (KaTeX left) in `compare/`.\n\n")
        report.append("| Suite | # | Score | Formula |\n|---|---|---|---|\n")
        val compare = File(reportDir, "compare").apply { mkdirs() }
        for (r in parsed.sortedBy { it.score.score }.take(WORST)) {
            report.append("| ${r.suite} | ${r.index} | ${format(r.score.score)} | `${r.formula.replace("|", "\\|")}` |\n")
            writeComparison(r, compare)
        }
        for ((r, _) in paired.sortedByDescending { it.second - it.first.score.score }.take(WORST)) writeComparison(r, compare)
        File(reportDir, "report.md").writeText(report.toString())
        println("KaTeX fidelity report: ${File(reportDir, "report.md").path}")
    }

    private fun writeComparison(r: Result, compare: File) {
        val suite = SUITES.first { it.name == r.suite }
        val references = File(System.getProperty("latex.katex.references") ?: File(root, "build/katex-references").path)
        val name = String.format(Locale.ROOT, "%04d.png", r.index)
        val reference = ImageIO.read(File(references, "${suite.references}/$name"))
        val ours = File(root, "latex-renderer/build/reports/katex-fidelity/renders/${r.suite}/$name").takeIf { it.isFile }?.let(ImageIO::read) ?: BLANK
        val height = maxOf(reference.height, ours.height)
        fun scaledWidth(image: BufferedImage) = (image.width * height.toDouble() / image.height).roundToInt()
        val gap = 16
        val out = BufferedImage(scaledWidth(reference) + gap + scaledWidth(ours), height, BufferedImage.TYPE_INT_RGB)
        val g = out.createGraphics()
        g.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BICUBIC)
        g.color = AwtColor.WHITE
        g.fillRect(0, 0, out.width, out.height)
        g.drawImage(reference, 0, 0, scaledWidth(reference), height, null)
        g.color = AwtColor.LIGHT_GRAY
        g.fillRect(scaledWidth(reference) + gap / 2 - 1, 0, 2, height)
        g.drawImage(ours, scaledWidth(reference) + gap, 0, scaledWidth(ours), height, null)
        g.dispose()
        ImageIO.write(out, "png", File(compare, "${r.suite}-$name"))
    }

    /** RaTeX's per-formula scores for main, in corpus order; null where RaTeX failed to render. */
    private fun ratexScores(file: File): List<Double?> {
        if (!file.isFile) return emptyList()
        val scores = Regex("\"scores\"\\s*:\\s*\\[([^\\]]*)]").find(file.readText())?.groupValues?.get(1) ?: return emptyList()
        return scores.split(',').map { it.trim().toDoubleOrNull() }
    }

    private fun format(value: Double) = String.format(Locale.ROOT, "%.3f", value)

    private companion object {
        /** Raster differences between machines move a score by well under this. */
        const val TOLERANCE = 0.02
        const val WORST = 60

        /** KaTeX's stylesheet sets `.katex { font-size: 1.21em }`, so its 20 px page draws 24.2 px math. */
        const val KATEX_EM_SCALE = 1.21f

        val SUITES = listOf(
            Suite("main.txt", "fixtures", 20),
            Suite("mhchem.txt", "fixtures_ce", 40),
            Suite("centernot.txt", "fixtures_centernot", 20),
            Suite("prooftree.txt", "fixtures_prooftree", 20, prooftree = true),
            Suite("slashed.txt", "fixtures_slashed", 20),
        )

        val root: File = generateSequence(File("").absoluteFile) { it.parentFile }.first { File(it, "test-corpus").isDirectory }

        val BLANK = BufferedImage(10, 10, BufferedImage.TYPE_INT_RGB).apply {
            createGraphics().apply { color = AwtColor.WHITE; fillRect(0, 0, 10, 10); dispose() }
        }

        val exporter by lazy {
            val density = Density(1f)
            LatexExporterState(
                density,
                TextMeasurer(createFontFamilyResolver(), density, LayoutDirection.Ltr),
                RendererRobustnessTest.fonts,
            )
        }
    }
}
